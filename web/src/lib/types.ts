// ---- LLM retry policy ----
// Two controls per retry layer; zero means unconfigured:
//   attempts: 0 = default; -1 disables this layer; positive = retry count
//   interval_ms: 0 = default exponential backoff; positive = fixed interval in milliseconds
export interface LLMRetryRule {
  attempts: number;
  interval_ms: number;
}

// Three endpoint-specific retry layers that profiles can override.
export interface LLMRetryOverride {
  connect: LLMRetryRule; // Connection retries before streaming: resets/timeouts/429/5xx
  empty: LLMRetryRule; // Empty-response retry after completion with no content (OpenAI format only)
  stream: LLMRetryRule; // Same-provider safe-window retry: replay interrupted stream before output delivery
}

// Global policy includes defaults for those three layers and two global-only layers:
//   breaker: attempts is consecutive transient failures before tripping; interval_ms is fixed cooldown
//   intent: rerun the whole intent after worker model_error
export interface LLMRetryPolicy extends LLMRetryOverride {
  breaker: LLMRetryRule;
  intent: LLMRetryRule;
}

