package server

import (
	"time"

	"github.com/Autumn-27/artex/agent"
	"github.com/Autumn-27/artex/db"
)

// Server-side retry policy resolution; see docs/LLM重试设计.md. Of the five layers:
//   - Connection, empty-response and same-provider safe-window retries follow the endpoint.
//     Each profile can override global defaults; unset fields inherit global or built-in defaults.
//   - Circuit breaking and intent replay are process-wide, with one global policy.
//
// Global policy reads one settings row per call. These are low-frequency paths (provider
// construction, work settlement and configuration saves), so no extra cache is needed.
// Circuit breaking is the exception: applyRetryPolicy pushes it to Registry for the failure path.

// retryPolicy reads the global policy; a nil DB yields the zero policy (all
// layers on their built-in defaults).
func (s *Server) retryPolicy() db.LLMRetryPolicy {
	if s.m == nil || s.m.pg == nil {
		return db.LLMRetryPolicy{}
	}
	return s.m.pg.LLMRetryPolicy()
}

// resolveRetry layers one profile's override on top of the global policy and
// converts the result into the form agent.Config carries. Rules combine field by
// field, so a profile that only pins an interval still inherits the global count.
func resolveRetry(o db.RetryOverride, pol db.LLMRetryPolicy) agent.RetryConfig {
	connect := o.Connect.Or(pol.Connect)
	empty := o.Empty.Or(pol.Empty)
	stream := o.Stream.Or(pol.Stream)
	return agent.RetryConfig{
		// Preserve count semantics: 0 = default, negative = disabled. SDK MaxRetries and
		// EmptyResponseRetries use exactly these semantics, so let the SDK resolve them.
		ConnectAttempts: connect.Attempts, ConnectInterval: connect.Interval(),
		EmptyAttempts: empty.Attempts, EmptyInterval: empty.Interval(),
		StreamAttempts: stream.Attempts, StreamInterval: stream.Interval(),
	}
}

// applyProfileRetry fills cfg.Retry for a profile read from the DB.
func (s *Server) applyProfileRetry(cfg *agent.Config, p *db.LLMProfile) {
	if p == nil {
		return
	}
	cfg.Retry = resolveRetry(p.Retry, s.retryPolicy())
}

// Circuit-breaker polling cooldown defaults match llmpool; override only explicitly configured values.
// Intent replay defaults are modelErrorRetries / modelErrorRetryBackoff in engine.go.

// applyRetryPolicy pushes the process-wide layers of the policy into the objects
// that consume them on a hot path: the circuit-breaker registry. Called at
// startup and whenever the policy is saved.
func (s *Server) applyRetryPolicy() {
	pol := s.retryPolicy()
	if s.llmHealth != nil {
		s.llmHealth.SetPolicy(pol.Breaker.Attempts, pol.Breaker.Interval())
	}
}

// modelErrorRetryPolicy resolves the intent-level replay knobs (layer ⑤): how
// many times a model_error work is re-run and how long to back off between runs.
func (e *Engine) modelErrorRetryPolicy() (retries int, backoff time.Duration) {
	retries, backoff = modelErrorRetries, modelErrorRetryBackoff
	if e == nil || e.m == nil || e.m.pg == nil {
		return retries, backoff
	}
	rule := e.m.pg.LLMRetryPolicy().Intent
	if rule.Attempts != 0 {
		retries = max(rule.Attempts, 0)
	}
	if d := rule.Interval(); d > 0 {
		backoff = d
	}
	return retries, backoff
}

// emptyTurnNudgeLimit resolves how many empty-turn continuations one work may
// inject (see steerHooks.Stop). It deliberately reuses the layer-2 empty-response retry count.
// Both layers address missing substantive output. The SDK resends the identical request when
// there are no content blocks; this layer appends an instruction when output contains only
// thinking, without body text or tools, so the model continues from its existing reasoning.
// Replaying identical input cannot fix context-shaped spinning. SDK emptiness is based on
// whether any event was yielded, and thinking deltas are events. Sharing the count matches
// the user intent: retry when the model has not produced substantive content.
//
// Read the global policy, not a profile override: failover can change profiles mid-run, but
// this is a whole-intent limit and must not change with endpoints. Like SDK emptyRetries():
// 0 = defaultEmptyTurnNudges; negative = disable empty-turn continuation; positive = that limit.
func (e *Engine) emptyTurnNudgeLimit() int {
	if e == nil || e.m == nil || e.m.pg == nil {
		return defaultEmptyTurnNudges
	}
	switch n := e.m.pg.LLMRetryPolicy().Empty.Attempts; {
	case n == 0:
		return defaultEmptyTurnNudges
	case n < 0:
		return 0
	default:
		return n
	}
}
